"""Настройки приложения. Читаются из переменных окружения или файла `.env`
в корне проекта (см. `.env.example`) через pydantic-settings."""

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    # --- Приложение ---
    APP_NAME: str = "polymarket_bot"
    LOG_LEVEL: str = "INFO"
    # Путь к файлу лога (с ротацией) - помимо вывода в stdout. Важно для
    # бота, который работает сутками на локальной машине без присмотра:
    # после падения/перезапуска нужно понять, что произошло, а не только
    # видеть последние строки в открытом терминале.
    LOG_FILE: str = "./data/bot.log"
    LOG_FILE_MAX_BYTES: int = 10_000_000
    LOG_FILE_BACKUP_COUNT: int = 5
    # Сторожевой таймер на полное зависание процесса: если event loop
    # перестанет отвечать дольше этого времени, в <LOG_FILE>_hang_dump.log
    # автоматически сбросятся стек-трейсы всех потоков - точная строка
    # кода, на которой всё встало. 0 = выключить.
    HANG_WATCHDOG_TIMEOUT_SECONDS: int = 90

    # --- База данных ---
    # По умолчанию - локальный файл SQLite, чтобы проект запускался без
    # дополнительной настройки. Для перехода на Postgres достаточно
    # поменять DATABASE_URL - модели SQLAlchemy от СУБД не зависят.
    DATABASE_URL: str = "sqlite+aiosqlite:///./data/polymarket.db"

    # --- Публичные API Polymarket (для чтения, авторизация не нужна) ---
    GAMMA_API_URL: str = "https://gamma-api.polymarket.com"
    CLOB_API_URL: str = "https://clob.polymarket.com"

    # --- Сборщик данных (Collector) ---
    RUN_COLLECTOR_IN_PROCESS: bool = True
    COLLECTOR_MARKET_LIMIT: int = 50
    COLLECTOR_INTERVAL_SECONDS: int = 60
    COLLECTOR_CONCURRENCY: int = 15
    # Отдельно от топа по объёму: страница за страницей собираем ВСЕ
    # активные NegRisk-рынки, иначе у многоисходного события (может быть
    # 10-20+ исходов) в топ-N по объёму попадут только 2-3 самых
    # популярных, а сканеру для convert_all/convert_single нужны ВСЕ
    # исходы с живым стаканом - без этого большинство событий никогда не
    # будет оценено целиком.
    COLLECTOR_NEGRISK_PAGE_SIZE: int = 100
    COLLECTOR_NEGRISK_MAX_PAGES: int = 20
    # Жёсткий потолок на число токенов, по которым запрашивается стакан
    # за один цикл сборщика. Применяется НА УРОВНЕ СОБЫТИЯ ЦЕЛИКОМ (все
    # исходы NegRisk-события группируются и берутся/пропускаются вместе,
    # приоритет - по суммарному объёму события) - событие никогда не
    # разрезается пополам, иначе сканер не сможет оценить его целиком.
    COLLECTOR_MAX_ORDERBOOK_TOKENS_PER_CYCLE: int = 600
    # Жёсткий таймаут на всю фазу сбора стаканов за цикл - если не
    # уложились, сохраняем то, что успели, и не блокируем следующий цикл.
    COLLECTOR_ORDERBOOK_PHASE_TIMEOUT_SECONDS: int = 90
    # Таймаут на один запрос стакана, независимо от retry - вторая линия
    # защиты от зависания сверх httpx-таймаута (10с) и retry (tenacity).
    COLLECTOR_ORDERBOOK_REQUEST_TIMEOUT_SECONDS: int = 15
    # Снепшоты стакана старше этого не нужны сканеру (ему важны только
    # последние несколько минут) - таблица append-only и иначе растёт
    # без ограничения. Чистка раз в N циклов, не каждый цикл.
    COLLECTOR_SNAPSHOT_RETENTION_HOURS: int = 24
    COLLECTOR_PRUNE_EVERY_N_CYCLES: int = 60
    # Жёсткий потолок на ВЕСЬ цикл сборщика целиком (метаданные + стаканы +
    # чистка) - последний рубеж защиты поверх таймаутов отдельных фаз и
    # запросов. Если что-то зависнет способом, который обошёл более точечные
    # таймауты (например, сама retry-логика tenacity внутри одного запроса
    # к Gamma), это всё равно оборвёт цикл и даст сборщику продолжить
    # работу на следующей итерации, а не замереть на часы.
    COLLECTOR_CYCLE_TIMEOUT_SECONDS: int = 180

    # --- Telegram (единственный интерфейс управления) ---
    TELEGRAM_BOT_TOKEN: str = ""
    # ID пользователей Telegram, которым разрешено управлять ботом (через
    # запятую в .env). Граница безопасности - без заполненного списка бот
    # отвечает "доступ запрещён" вообще всем.
    TELEGRAM_ADMIN_IDS: str = ""
    RUN_TELEGRAM_BOT_IN_PROCESS: bool = True

    # --- Polygon / on-chain (Convert через NegRiskAdapter) ---
    # Публичный RPC по умолчанию годится для чтения, но для боевой работы
    # настоятельно рекомендуется платный RPC (Alchemy/Infura/Dwellir и
    # т.п.) - публичные эндпоинты жёстко лимитируют запросы и будут
    # молча тормозить стратегию в самый неподходящий момент.
    POLYGON_RPC_URL: str = "https://polygon-rpc.com"
    # Таймаут одного HTTP-запроса к RPC. ВАЖНО: web3 синхронный, поэтому
    # любой вызов цепочки из async-кода обязан идти через
    # asyncio.to_thread (иначе он блокирует весь event loop, включая
    # FastAPI) - именно так бот однажды замирал на часы.
    POLYGON_RPC_TIMEOUT_SECONDS: int = 10

    # Адреса сверены по официальной странице
    # https://docs.polymarket.com/resources/contracts (актуальна на момент
    # написания). Это контракты позиционных токенов (CTF) и коллатерала -
    # отдельные от контрактов биржи CLOB (их адреса не нужны напрямую,
    # ими занимается py-clob-client-v2), поэтому миграция на CLOB V2/pUSD
    # в апреле 2026 их не затронула. Всё равно стоит сверить ещё раз по
    # ссылке выше перед торговлей на существенную сумму - адреса контрактов
    # ровно то, во что нельзя слепо верить на слово LLM.
    NEG_RISK_ADAPTER_ADDRESS: str = "0xd91E80cF2E7be2e162c6513ceD06f1dD0dA35296"
    CTF_ADDRESS: str = "0x4D97DCd97eC945f40cF65F87097ACe5EA0476045"
    # pUSD - коллатерал всех сделок на Polymarket после миграции на V2,
    # обычный ERC-20, 6 знаков после запятой.
    PUSD_ADDRESS: str = "0xC011a7E12a19f7B1f670d46F03B03f3342E82DFB"

    # Публичный адрес кошелька - для чтения баланса/позиций.
    WALLET_ADDRESS: str = ""

    # Приватный ключ (hex). Читается только из .env, никогда не
    # логируется. Самый простой вариант хранения ключа (обычная переменная
    # окружения) - годится для личного бота на одной машине, не замена
    # полноценному менеджеру секретов, если бот когда-нибудь переедет на
    # общую инфраструктуру.
    WALLET_PRIVATE_KEY: str = ""

    # Тип подписи для CLOB (см. py-clob-client-v2 / доки Polymarket):
    # 0 = обычный EOA-кошелёк (тот же адрес подписывает и держит средства).
    # 1/2/3 = варианты proxy/deposit-кошельков (вход через email/Magic,
    # Gnosis Safe, POLY_1271). Если аккаунт заведён через сайт Polymarket
    # (email/соцсети) - почти наверняка нужен не 0, а один из этих
    # вариантов, и WALLET_FUNDER_ADDRESS должен быть адресом, который
    # реально держит средства (смотрите в профиле на polymarket.com),
    # а не обязательно тем же адресом, что выводится из WALLET_PRIVATE_KEY.
    WALLET_SIGNATURE_TYPE: int = 0
    WALLET_FUNDER_ADDRESS: str = ""

    # Общий аварийный выключатель для всего, что подписывает и отправляет
    # транзакции (Convert, покупка/продажа через CLOB). Должен быть явно
    # включён в .env - и даже тогда каждое место вызова само по себе
    # требует confirm=True, прежде чем что-то коснётся реальных денег.
    ENABLE_ONCHAIN_EXECUTION: bool = False

    # --- Управление капиталом ---
    # Отправная точка капитала - используется только как запасной вариант,
    # если живой баланс кошелька прочитать не удалось (RPC недоступен и
    # т.п.) И только для первого запуска, когда в БД ещё нет истории. В
    # норме бот размер сделки считает от РЕАЛЬНОГО баланса pUSD на
    # кошельке, а не от этого числа - так происходит накопление капитала:
    # баланс вырос -> следующие сделки крупнее, баланс упал -> мельче.
    STARTING_BANKROLL_USD: float = 100.0

    # --- Лимиты риска исполнения ---
    # Доля ТЕКУЩЕГО (живого) баланса на одну сделку и на день - а не
    # фиксированная сумма в долларах, чтобы лимиты сами росли вместе с
    # капиталом. При $100 и EXECUTION_TRADE_FRACTION=0.08 это ~$8 на
    # сделку; когда баланс дорастёт до $500 - уже ~$40, без ручной правки.
    EXECUTION_TRADE_FRACTION: float = 0.08
    EXECUTION_DAILY_FRACTION: float = 0.30
    # Абсолютные потолки поверх долевых - подстраховка на случай, если
    # баланс внезапно сильно вырастет, а риск-параметры подправить забыли.
    EXECUTION_MAX_NOTIONAL_PER_TRADE: float = 100.0
    EXECUTION_DAILY_NOTIONAL_CAP: float = 300.0
    # Прервать сделку, если цена к моменту реального исполнения ушла хуже
    # той, что использовал сканер, больше чем на эту долю.
    EXECUTION_MAX_SLIPPAGE_PCT: float = 0.02
    RUN_EXECUTOR_IN_PROCESS: bool = False
    EXECUTOR_POLL_INTERVAL_SECONDS: int = 5
    # Если живой баланс прочитать не удалось - пропустить цикл исполнения
    # целиком (не торговать "вслепую" по устаревшей/угаданной цифре).
    # Это всегда true и не выносится в настройку намеренно: отказ от
    # торговли при неизвестном балансе - не та защита, которую стоит
    # давать отключать.

    # --- Сканер арбитража NegRisk ---
    # Запасная оценка комиссии (б.п.), если getFeeBips() недоступен -
    # уточняется по каждому рынку отдельно, когда RPC отвечает.
    NEGRISK_FEE_BIPS_FALLBACK: int = 0
    # Живая комиссия читается с цепочки ТОЛЬКО для событий, где уже есть
    # кандидат на возможность (без комиссии она лишь уменьшает прибыль,
    # так что отсев по нулевой комиссии безопасен) - и не более стольки
    # запросов за цикл, чтобы публичный RPC не лимитировал.
    NEGRISK_MAX_FEE_LOOKUPS_PER_CYCLE: int = 20
    # Минимальная ожидаемая прибыль (доля от суммы сделки, 0.01 = 1%),
    # ниже которой сканер не считает это возможностью вообще.
    NEGRISK_MIN_PROFIT_PCT: float = 0.01
    # Размер (в единицах токена-исхода), на который сканер оценивает
    # возможности при обходе стакана. Не определяет реальный размер
    # сделки (это делает Executor от живого баланса) - просто гранулярность
    # сканирования; большие значения точнее отражают глубину рынка, но
    # медленнее считаются.
    NEGRISK_SCAN_SIZE: float = 10.0
    NEGRISK_SCAN_INTERVAL_SECONDS: int = 30
    RUN_SCANNER_IN_PROCESS: bool = True


@lru_cache
def get_settings() -> Settings:
    return Settings()
